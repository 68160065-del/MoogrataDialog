    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        int row = tblMenu.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "เลือกเมนูจากตารางซ้ายก่อน",
                    "ยังไม่ได้เลือกเมนู", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int qty;
        try {
            qty = Integer.parseInt(txtQty.getText().trim());
        } catch (NumberFormatException ex) {
            qty = 0;
        }
        if (qty < 1) {
            JOptionPane.showMessageDialog(this, "จำนวนต้องเป็นตัวเลขตั้งแต่ 1 ขึ้นไป",
                    "จำนวนไม่ถูกต้อง", JOptionPane.WARNING_MESSAGE);
            return;
        }
        MenuItem chosen = menuItems.get(row);   // เมนูของแถวที่เลือก (loadMenu เก็บ object ไว้ให้แล้ว)
// บันทึกลงฐานข้อมูลทันที — กฎทำงานใน BillService หน้าจอไม่เขียน SQL เอง
        BillItem saved = billService.addItem(bill, chosen, qty);
        if (saved == null) {
            JOptionPane.showMessageDialog(this, "บันทึกรายการไม่สำเร็จ",
                    "ผิดพลาด", JOptionPane.ERROR_MESSAGE);
            return;
        }
        txtQty.setText("1");
        refreshBill();
    }//GEN-LAST:event_btnAddActionPerformed

