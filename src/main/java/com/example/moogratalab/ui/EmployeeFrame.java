    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        EmployeeDialog dialog = new EmployeeDialog(this, "เพิ่มพนักงานใหม่");
        dialog.setVisible(true);            // modal — โปรแกรมรอตรงนี้จนกว่า dialog จะถูกปิด
        if (dialog.isSaved()) {
            showEmployees();                // ข้อมูลเปลี่ยน → อ่านใหม่จากฐานข้อมูล
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        int row = tblEmployee.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this,
                "เลือกพนักงานในตารางก่อนกดแก้ไข",
                "ยังไม่ได้เลือก", JOptionPane.WARNING_MESSAGE);
        return;
    }
    int id = (Integer) tblEmployee.getValueAt(row, 0);
    Employee emp = employeeService.get(id);
    if (emp == null) {
        JOptionPane.showMessageDialog(this,
                "หาพนักงานรหัส " + id + " ไม่พบ (อาจถูกลบไปแล้ว)",
                "ไม่พบข้อมูล", JOptionPane.ERROR_MESSAGE);
        return;
    }
    EmployeeDialog dialog = new EmployeeDialog(this, "แก้ไขพนักงาน: " + emp.getName(), emp);
    dialog.setVisible(true);
    if (dialog.isSaved()) {
        showEmployees();
    }
    }//GEN-LAST:event_btnEditActionPerformed

